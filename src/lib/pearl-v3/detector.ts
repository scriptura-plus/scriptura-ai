const SYSTEM = `Ты — внимательный читатель библейского текста, ищущий наблюдения для зрелой аудитории, которая знает Библию десятилетиями.

Твоя задача — НЕ писать готовые карточки, НЕ проповедовать и НЕ делать общий комментарий к стиху.
Твоя задача — собрать качественные наблюдения-углы, которые могут стать сырьём для следующего этапа.

Главная дисциплина: ищи только то, что видно в предоставленном русском тексте стиха и главы. Не используй греческий, еврейский, арамейский язык и не превращай работу в анализ морфологии русского перевода.`;

function buildUserPrompt(ctx: PearlV3VerseContext): string {
  return `ВХОДНЫЕ ДАННЫЕ

ЦЕНТРАЛЬНЫЙ СТИХ
${ctx.centralRef}
«${ctx.centralText}»

КОНТЕКСТ
Вся глава, центральный стих помечен [ЦЕНТР]:

${ctx.chapterText}

ЗАДАЧА

Найди в ЦЕНТРАЛЬНОМ стихе все заметные рабочие углы, которые в нём честно есть.

Угол — это наблюдение о конкретном месте в тексте, которое может вызвать у зрелого читателя ощущение:

«Этого я не замечал»
или
«Так я ещё не входил в этот стих».

Твоя задача — НЕ писать карточки. Только собрать сырьё: якорь, наблюдение и почему это интересно.

ГЛАВНОЕ ПРАВИЛО КОЛИЧЕСТВА

Нет обязательного минимума.

Дай столько углов, сколько стих честно даёт:

— плотный, дефиниционный, риторически насыщенный стих может дать 15–30 углов;
— повествовательный или диалогический стих обычно даёт 6–12 углов;
— бедный стих — родословие, список, техническое описание, краткая связка, рефрен — часто даёт 1–4 угла;
— в редком случае стих может дать 0 рабочих углов сам по себе.

Не добирай ради числа.
Не округляй до красивого количества.
Не делай вид, что бедный стих богатый.
Лучше вернуть 4 честных угла, чем 14 полууглов.

ИСТОЧНИК ОЖИДАНИЯ

Большая часть углов — особенно отрицательных, риторических, структурных и контекстуальных — строится на контрасте: что-то замечено на фоне ожидания.

При каждом таком угле спрашивай себя: откуда у меня это ожидание?

Допустимые источники ожидания:

— сам центральный стих: его синтаксис, параллелизм, формула, порядок, ход мысли;
— ближайший контекст главы;
— остальная книга того же автора — только если наблюдение касается повторов, композиции или функции фразы в пределах этой книги;
— другие книги Писания — только если в центральном стихе есть прямая цитата или явная аллюзия.

Недопустимые источники ожидания:

— богословская традиция, догматика, систематическое богословие;
— то, «как обычно говорят» про этот стих в комментариях;
— то, что «обычно бывает» в подобных текстах вообще;
— другие места Писания, на которые стих сам не ссылается.

Если для того, чтобы заметить нечто в стихе, тебе нужно сначала привнести внешнюю рамку, — это не угол, а проекция. Не включай.

РЕЖИМ РАБОТЫ

Не отбирай только самые эффектные углы.
Не распределяй углы «справедливо» по частям стиха.
Иди туда, где текст реально плотный.

Но при этом отсекай мусор:

— слабые догадки;
— повторения;
— очевидные перефразы;
— моральные выводы;
— красивые, но не текстовые мысли;
— углы, которые держатся только на грамматике или словообразовании русского перевода;
— углы, которые требуют оригинального языка.

Работай несколькими проходами. На каждом проходе спрашивай:

— что здесь сказано?
— что НЕ сказано, хотя сам текст создал ожидание?
— почему такой порядок?
— что соединено?
— что разделено?
— кто действует?
— кто говорит?
— кто молчит?
— кто назван?
— кто не назван?
— что стих предполагает известным и не объясняет?
— какую функцию стих выполняет в ближайшей сцене или ходе главы?

ПРОХОДЫ

1. Слово и фраза в русском тексте.
Ищи заметные слова, имена, титулы, повторы, уточнения, союзы, предлоги, формулы и отсутствие ожидаемых уточнений. Не анализируй морфологию слова.

2. Внутренние связки стиха.
Что с чем соединено; какой порядок; где рамка; что повторено; что единственно; что параллельно; что нарушает параллель.

3. Адресаты, голоса и действия.
Кто говорит, кому, при ком; кто действует; кто претерпевает; кто назван; кто не назван; есть ли смена лица, голоса, адресата или перспективы.

4. Жанр и умолчания.
Стих ведёт себя как молитва, учение, формула, нарратив, перечень, родословие, техническая пометка, переход?
Есть ли жанровый сбой?
Что стих считает очевидным и не объясняет?

5. Контекст главы.
Что центральный стих подхватывает, обрывает, определяет, уточняет, отрицает или завершает?
На какой вопрос главы он отвечает?
К какой формулировке глава шла?
Какую функцию стих выполняет в своём месте?

ВЕС ПРОХОДОВ

Вес проходов зависит от типа стиха.

На плотном, дефиниционном, богословски или риторически насыщенном стихе главные проходы: 1, 2, 4.

На повествовательном или диалогическом стихе главные проходы: 3, 5.

На бедном стихе почти весь вес может лечь на проход 5. Остальные проходы могут почти ничего не дать, и это нормально.

ЧТО ИСКАТЬ

Это палитра, а не чек-лист. Если категория не работает на этом стихе — не используй её.

Структурные углы:

— асимметрия;
— порядок;
— первое и последнее место;
— центр и периферия;
— повтор;
— единственный элемент;
— симметрия;
— нарушение симметрии;
— необычная композиция внутри стиха;
— позиция стиха в сцене.

Риторические углы:

— на чём держится утверждение;
— где мысль смягчена;
— где усилена;
— где есть инверсия, парадокс, напряжение, тавтология, плеоназм;
— что опущено как будто очевидное;
— где молчание текста само работает как приём.

Нарративные углы:

— кто действует;
— кто реагирует;
— кто молчит;
— кто назван или не назван;
— какие роли распределены;
— есть ли смена голоса, лица, адресата или перспективы;
— как стих двигает сцену.

Логические углы:

— что связывают «ибо», «потому что», «итак», «и», «же», «но»;
— есть ли причина, следствие, условие, вывод;
— где определение встроено в молитву, рассказ, наставление или список;
— где стих отвечает на вопрос, поставленный раньше.

Синтаксические углы в русском тексте:

— порядок слов;
— повтор слов или конструкций;
— соединение фраз;
— разрыв ожидаемой связки;
— отсутствие пояснения;
— необычная позиция фразы внутри стиха;
— связь центрального стиха с соседними репликами или действиями.

Не строй отдельные углы на виде глагола, приставках, суффиксах, падежах или тонкой грамматике русского перевода.

Словесные углы без лингвистического анализа:

— слово выступает как имя, титул, роль или формула;
— слово повторяется или противопоставлено соседнему слову;
— слово занимает заметную позицию в структуре стиха;
— слово важно для связи центрального стиха с ближайшим контекстом.

Не анализируй этимологию, приставки, суффиксы, морфологию или скрытые оттенки русского слова.

Отрицательные углы:

Отрицательный угол допускается только тогда, когда ожидание присутствия чего-либо создано самим текстом: его синтаксисом, параллелизмом, жанровой формулой, явным ходом ближайшего контекста или лексической рамкой стиха.

Можно искать:

— что НЕ сказано, хотя стих сам создал ожидание этого;
— кого НЕ названо, хотя стих перечисляет рядом стоящих;
— какого уточнения нет, хотя соседнее уточнение задало шаблон;
— какой связки нет, хотя жанр или конструкция её требуют;
— где молчание текста само становится наблюдением, потому что текст подвёл к месту, где должно было что-то быть.

Отрицательный угол не допускается, если ожидание привнесено догматикой, традицией, корпусом, комментаторской темой или другими местами Писания, на которые стих не ссылается.

Контекстуальные углы:

Градация допустимого контекста:

— ближайший контекст главы — всегда;
— остальная книга того же автора — только если наблюдение касается повторов, композиции или функции фразы в пределах этой книги;
— другие книги Писания — только при прямой цитате или явной аллюзии в самом центральном стихе.

Что искать:

— эхо предыдущих стихов;
— сдвиг относительно предыдущего хода мысли;
— стих как ответ на вопрос, заданный раньше;
— стих как формулировка, к которой глава шла;
— позиция стиха в ряду, списке, родословии, повторяющейся формуле или развитии сцены;
— повторы, рамки, уникальные функции фраз в пределах книги.

СТРОГИЙ ЗАПРЕТ: ОРИГИНАЛЬНЫЙ ЯЗЫК

В этой линзе запрещено использовать греческий, еврейский или арамейский язык.

Не упоминай:

— греческие, еврейские или арамейские слова;
— транслитерации;
— леммы;
— морфологию;
— Strong’s numbers;
— утверждения вида «в греческом стоит…», «в оригинале сказано…», «это аорист…», «это форма настоящего времени…».

Даже если ты знаешь оригинальный язык из памяти, не используй его.

Если угол требует оригинального языка, НЕ включай его здесь. Такой угол принадлежит отдельной линзе «Лексика».

В этой линзе разрешены только:

— русский текст центрального стиха;
— русский текст ближайшего контекста главы;
— структура;
— порядок слов;
— повторы;
— умолчания;
— контрасты;
— позиция стиха в сцене;
— функция стиха в ближайшем контексте.

СТРОГИЙ ЗАПРЕТ: РУССКАЯ МОРФОЛОГИЯ И СЛОВООБРАЗОВАНИЕ

Не превращай Pearl-линзу в анализ русского слова.

Не включай углы, если главный смысл держится на:

— приставке русского слова;
— суффиксе;
— этимологии;
— морфологии;
— виде глагола;
— падеже;
— тонком различии русских синонимов;
— школьной формуле вроде «совершенный вид = однократное действие».

Даже если такой угол кажется красивым, не включай его здесь. Он принадлежит отдельной лексической линзе или ручной редакторской проверке.

Можно замечать русский текст только на уровне обычного чтения:

— какое слово стоит в центре;
— какое слово повторяется;
— какое слово противопоставлено соседнему;
— какое слово названо или не названо;
— где слово стоит в структуре фразы;
— как фраза работает в сцене.

ЧТО НЕ ВКЛЮЧАТЬ

Не включай:

— общие моральные выводы;
— перефразы стиха другими словами;
— проповеднические применения;
— внешнюю историческую, культурную, археологическую или биографическую справку;
— сравнение переводов;
— анализ оригинального языка;
— анализ морфологии русского слова;
— богословские синтезы, которые не растут из конкретного слова, фразы или структуры центрального стиха;
— справку ради справки.

ПСЕВДО-УГЛЫ

Если угол попадает в одну из категорий ниже — не включай его:

1. Проекционный угол.
Ожидание привнесено извне.

2. Эхо корпуса.
Наблюдение держится не на самом тексте, а на стандартной теме обсуждения.

3. Декоративный якорь.
Названо конкретное слово, но наблюдение не зависит от именно этого слова.

4. Инфляция значимости.
Нейтральная конструкция подана как удивительная или редкая.

5. Угол-на-домысле.
Наблюдение требует допущения, которого в тексте нет.

6. Морфологический угол.
Наблюдение держится на виде глагола, приставке, суффиксе, падеже или тонком грамматическом анализе русского перевода.

АНТИ-ДУБЛИРОВАНИЕ

Не включай два угла, если у них:

— один и тот же якорь;
— одно и то же наблюдение;
— один и тот же смысловой сдвиг.

Если два угла отличаются только формулировкой, объедини их.

Разделяй углы только тогда, когда они действительно открывают разные стороны текста.

Одно плотное место в стихе может дать 2–4 разных угла, если меняется хотя бы одно из трёх:

— фокус наблюдения;
— вопрос к тексту;
— смысловой сдвиг для читателя.

ФИЛЬТР ПЕРЕД ВЫХОДОМ

Перед тем как включить угол, проверь:

1. Это наблюдение про конкретное место в центральном стихе?
2. Якорь — реальное слово, фраза или место в стихе, а не пересказ?
3. Если подставить вместо этого слова/фразы близкий синоним или нейтральный вариант — наблюдение изменится?
4. Это даёт зрелому читателю либо открытие, либо новый вход?
5. Это не банальность?
6. Это не моральный вывод?
7. Это не внешняя справка?
8. Это не дубль другого угла?
9. Если угол строится на контрасте, асимметрии, отсутствии, неожиданности — источник ожидания находится в самом тексте, ближайшем контексте или книге того же автора?
10. Не нужно ли допущение, которого в тексте нет?
11. Не держится ли угол на оригинальном языке?
12. Не держится ли угол на морфологии, приставке, суффиксе или тонком грамматическом анализе русского перевода?

Если хотя бы один ответ «нет» — не включай.

ФОРМАТ ОТВЕТА

Строго следуй формату.
Ничего лишнего перед ответом и после ответа не добавляй.

УГОЛ 1

Тип: <структурный / риторический / нарративный / логический / синтаксический / словесный / отрицательный / контекстуальный>

Якорь: <конкретное слово, фраза или место в центральном стихе>

Наблюдение: <что замечено; 2–4 строки>

Почему интересно: <почему это может быть открытием или новым входом для зрелого читателя; 1–2 строки>

УГОЛ 2

Тип: ...

Якорь: ...

Наблюдение: ...

Почему интересно: ...

Продолжай до исчерпания рабочих углов, которые стих честно даёт.

Если рабочих углов нет, напиши:

УГЛОВ НЕТ

Мета-нота: <1–2 строки о том, почему стих беден сам по себе и какую функцию он выполняет в главе, списке, родословии, переходе или композиции>

В конце всегда добавь короткий самоотчёт:

Не прошёл / прошёл слабо: <1–3 строки о том, какие траектории по этому стиху не развернулись и почему>

Это не самокритика. Это карта слепых зон для следующего этапа.`;
}

export async function runPearlV3Detector(
  ctx: PearlV3VerseContext,
): Promise<{ rawOutput: string; angles: PearlV3Angle[] }> {
  const rawOutput = await callPearlClaude({
    system: SYSTEM,
    user: buildUserPrompt(ctx),
    maxTokens: 8000,
  });

  return {
    rawOutput,
    angles: parseAngles(rawOutput),
  };
}

function parseAngles(raw: string): PearlV3Angle[] {
  if (/^\s*УГЛОВ\s+НЕТ\b/i.test(raw.trim())) {
    return [];
  }

  const blocks = raw.split(/\n(?=УГОЛ\s+\d+)/i);
  const angles: PearlV3Angle[] = [];

  for (const block of blocks) {
    const headerMatch = block.trimStart().match(/^УГОЛ\s+(\d+)/i);
    if (!headerMatch) continue;

    const index = Number(headerMatch[1]);
    if (!Number.isFinite(index)) continue;

    const anchor = cleanExtractedField(extractField(block, "Якорь"));
    const observation = cleanExtractedField(extractField(block, "Наблюдение"));
    const whyInteresting = cleanExtractedField(
      extractField(block, "Почему интересно"),
    );

    if (!anchor || !observation) continue;

    angles.push({
      index,
      anchor,
      observation,
      whyInteresting: whyInteresting ?? "",
    });
  }

  return angles;
}

function extractField(block: string, label: string): string | null {
  const labels = [
    "Тип",
    "Якорь",
    "Наблюдение",
    "Почему интересно",
    "Мета-нота",
    "Не прошёл / прошёл слабо",
    "Не прошел / прошел слабо",
  ];

  const others = labels
    .filter((item) => item !== label)
    .map((item) => `${item}:`);

  const stopPattern = [...others, "УГОЛ ", "---"]
    .map((item) => item.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
    .join("|");

  const re = new RegExp(
    `${label}:\\s*([\\s\\S]*?)(?=\\n\\s*(?:${stopPattern})|$)`,
    "i",
  );

  const match = block.match(re);
  if (!match) return null;

  return match[1].trim();
}

function cleanExtractedField(value: string | null): string | null {
  if (!value) return null;

  return value
    .replace(/\n\s*-{3,}\s*$/g, "")
    .replace(/\s+$/g, "")
    .trim();
}