export async function runPearlV3Writer(
  ctx: VerseContext,
  angle: Angle
): Promise<{ rawOutput: string; pearl: Pearl | null; card: PearlV3CardDraft | null }> {
  const rawOutput = await callPearlClaude({
    system: SYSTEM,
    user: buildUserPrompt(ctx, angle),
    maxTokens: 2000,
  });

  const pearl = parsePearl(rawOutput);
  return {
    rawOutput,
    pearl,
    card: pearl
      ? {
          title: pearl.title,
          anchor: pearl.anchorQuote,
          teaser: pearl.body,
          why_it_matters: pearl.whyMatters,
        }
      : null,
  };
}

function parsePearl(raw: string): Pearl | null {
  const cleaned = raw
    .trim()
    .replace(/^```(?:json)?\s*/i, "")
    .replace(/\s*```$/i, "")
    .trim();

  try {
    const parsed = JSON.parse(cleaned) as Partial<Record<keyof Pearl, unknown>>;
    const title = toNonEmptyString(parsed.title);
    const anchorQuote = toNonEmptyString(parsed.anchorQuote);
    const body = toNonEmptyString(parsed.body);
    const whyMatters = toNonEmptyString(parsed.whyMatters);

    if (!title || !anchorQuote || !body || !whyMatters) return null;

    return { title, anchorQuote, body, whyMatters };
  } catch {
    return null;
  }
}

function toNonEmptyString(value: unknown): string | null {
  if (typeof value !== "string") return null;
  const trimmed = value.trim();
  return trimmed ? trimmed : null;
}








