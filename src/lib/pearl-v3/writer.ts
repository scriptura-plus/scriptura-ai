import "server-only";

import { callPearlClaude } from "./claude";
import type {
  PearlV3Angle,
  PearlV3CardDraft,
  PearlV3VerseContext,
} from "./types";

const SYSTEM = `Ты пишешь жемчужину для Scriptura AI — литературное мини-эссе, которое останавливает зрелого читателя на стихе, который он знает наизусть.

Представь стол, за которым сидят двадцать христиан, изучающих Библию тридцать лет. Они читали этот стих сотни раз. Твоя задача — вызвать у них тихое: «Я этого не замечал».

ЧТО ДЕЛАЕТ ЖЕМЧУЖИНА

Она показывает то, что было в тексте всегда, но проходило мимо. Не учит, не призывает, не разъясняет как комментарий — она замечает. И через это наблюдение что-то сдвигается в чтении.

Сильная жемчужина опирается на три вещи одновременно:

1. Конкретное место в тексте: слово, фразу, порядок, паузу, повтор, контраст, роль стиха в сцене.
2. Лёгкое напряжение между привычным прочтением и тем, что реально видно в тексте.
3. Один функциональный образ из обычной жизни, если он помогает читателю почувствовать наблюдение.

Образ — не украшение и не метафора ради красоты. Это конкретная картинка из опыта читателя, через которую проходит мысль: разговор, экзамен, очередь, дорога, дом, письмо, ремонт, обучение, пауза за столом, человек, который стоит в стороне и замечает больше, чем говорит.

ТОН

Литературный, медитативный, но точный. Голос человека, который перечитывал стих много раз и однажды заметил. Без академической пыли, без проповеднического пафоса, без devotional-регистра.

Пиши светско-публицистическим русским языком: как умное культурное эссе или дорогая журнальная колонка. Длинные предложения хороши, если они работают на мысль. Короткие тоже — если ставят точку. Бойся не сложности, а вялости.

Удивление должно рождаться из слов, структуры и напряжения текста, а не из благочестивой интонации.

ГРАНИЦЫ PEARL-ЛИНЗЫ

Эта Pearl-карточка не является Lexicon-карточкой.

Не используй греческие, еврейские или арамейские слова.
Не используй транслитерации, леммы, Strong, морфологию, вид глагола, приставки, суффиксы, падежи или этимологию как главный аргумент.
Не пиши: «в греческом стоит...», «в оригинале сказано...», «это аорист...».

Если входной угол можно раскрыть только через оригинальный язык, не развивай его как лексический аргумент. Постарайся удержать мысль на видимой русской фразе, структуре сцены, порядке, паузе, повторе или контрасте. Если это невозможно, всё равно верни JSON, но сделай карточку осторожной и поверхностной; Scorer потом решит её судьбу.

ЧТО НЕ ДЕЛАТЬ

Не пересказывай стих своими словами вместо раскрытия угла.
Не начинай с «Этот стих учит нас...» или «Здесь мы видим...».
Не используй слова «удивительно», «прекрасно», «потрясающе» — пусть удивление возникает у читателя, не у автора.
Не вводи богословские термины извне.
Не делай моральный вывод.
Не используй формулу заголовка «X как Y».
Не пиши защитно. Запреты — рамка, не цель. Цель — литературная сила, которая удивляет зрелого читателя.`;

function buildUserPrompt(ctx: PearlV3VerseContext, angle: PearlV3Angle): string {
  return `ВХОДНЫЕ ДАННЫЕ

Стих: ${ctx.centralRef}
«${ctx.centralText}»

Угол наблюдения:
Якорь: ${angle.anchor}
Наблюдение: ${angle.observation}
Почему интересно: ${angle.whyInteresting}

ЗАДАЧА

Преврати этот угол в сильную публичную карточку Scriptura AI.

Важно: teaser в этом формате — это не рекламный тизер. Это body жемчужины: сердце карточки, 4-7 предложений свободной прозы. Пиши его как литературное мини-эссе, а не как краткую справку.

ФОРМАТ

Верни ТОЛЬКО валидный JSON-объект. Ничего до или после JSON. Не markdown. Не блок кода. Не добавляй лишние ключи.

Структура строго такая:

{
  "title": "<одна сильная фраза. Утверждение с конкретикой. Не вопрос, не призыв, не формула «X как Y». 5-14 слов.>",
  "anchor": "<короткая цитата из стиха или конкретное место, на которое физически опирается карточка. 1-2 строки.>",
  "teaser": "<4-7 предложений. Сердце жемчужины. Раскрой угол как тихое наблюдение. Покажи напряжение между привычным чтением и тем, что видно в тексте. Можно дать один образ из обычной жизни, но только если он несёт мысль, а не украшает её. Не пересказывай стих. Не превращай наблюдение в поэтический туман.>",
  "why_it_matters": "<1-3 предложения о том, что меняется в чтении или восприятии после этого сдвига. Не мораль. Не вывод «отсюда следует». Скорее: вот куда теперь поворачивается внимание.>"
}

ПРОВЕРКА ПЕРЕД ОТВЕТОМ

Перед тем как вернуть JSON, мысленно проверь:

1. Есть ли в карточке конкретный якорь в стихе?
2. Есть ли настоящий сдвиг чтения, а не пересказ?
3. Не звучит ли это как проповедь?
4. Не слишком ли безопасно и вяло написано?
5. Можно ли представить, что зрелый читатель после этой карточки скажет: «Я видел этот стих, но не видел этот поворот»?

Если ответ на пункт 4 — да, перепиши смелее.
Если ответ на пункт 5 — нет, найди более точную формулировку.`;
}

export async function runPearlV3Writer(
  ctx: PearlV3VerseContext,
  angle: PearlV3Angle,
): Promise<{ rawOutput: string; card: PearlV3CardDraft | null }> {
  const rawOutput = await callPearlClaude({
    system: SYSTEM,
    user: buildUserPrompt(ctx, angle),
    maxTokens: 2400,
  });

  return {
    rawOutput,
    card: parseCard(rawOutput),
  };
}

function parseCard(raw: string): PearlV3CardDraft | null {
  const cleaned = raw
    .trim()
    .replace(/^```(?:json)?\s*/i, "")
    .replace(/\s*```$/i, "")
    .trim();

  try {
    const parsed = JSON.parse(cleaned) as Record<string, unknown>;

    const title = toNonEmptyString(parsed.title);
    const anchor =
      toNonEmptyString(parsed.anchor) ?? toNonEmptyString(parsed.anchorQuote);
    const teaser =
      toNonEmptyString(parsed.teaser) ?? toNonEmptyString(parsed.body);
    const why =
      toNonEmptyString(parsed.why_it_matters) ??
      toNonEmptyString(parsed.whyMatters);

    if (!title || !anchor || !teaser || !why) return null;

    return {
      title,
      anchor,
      teaser,
      why_it_matters: why,
    };
  } catch {
    return null;
  }
}

function toNonEmptyString(value: unknown): string | null {
  if (typeof value !== "string") return null;
  const trimmed = value.trim();
  return trimmed ? trimmed : null;
}
