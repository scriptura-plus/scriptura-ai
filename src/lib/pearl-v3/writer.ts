import "server-only";

import { callPearlClaude } from "./claude";
import type {
  PearlV3Angle,
  PearlV3CardDraft,
  PearlV3VerseContext,
} from "./types";

const SYSTEM = `Ты пишешь короткую карточку-жемчужину для Scriptura AI по стиху Библии.

Это не справка, не комментарий и не проповедь. Это сдвиг в чтении.

Представь стол, за которым сидят двадцать христиан, изучающих Библию тридцать лет. Они знают этот стих наизусть. Твоя задача — вызвать у них тихое «вау, я этого не замечал».

ТОН

Тихое наблюдение. Литературный, медитативный, но точный. Без академической пыли, без проповеднического пафоса. Не лекция, не назидание. Звучит как голос человека, который перечитывал стих много раз и однажды заметил.

РЕГИСТР

Пиши светско-публицистическим русским языком: как умное культурное эссе или дорогая журнальная колонка. Без церковного, проповеднического и devotional-регистра.

Удивление должно рождаться из слов, структуры и напряжения текста, а не из благочестивой интонации.

ТЕКСТУАЛЬНАЯ ТОЧНОСТЬ — ГЛАВНОЕ ПРАВИЛО

Работай только с тем, что реально поддерживает сам стих, ближайший контекст главы или проверенные оригинально-языковые данные, если они явно даны в угле. Не вводи богословские термины извне — даже если стих очевидно к ним отсылает.

Запрещённые слова, если их нет прямо в стихе или в проверенной оригинально-языковой опоре: «крест», «распятие», «Голгофа», «искупление», «жертва», «Спаситель», «грехопадение», «Богочеловек», «триединство», «таинство», «благодать», «спасение».

Это не цензура. Это требование к точности: жемчужина должна работать на словах, которые в тексте, а не на словах, которые читатель уже знает из проповедей.

ФОРМАТ SCRIPTURA AI

Ты возвращаешь не лабораторный текст, а продуктовую карточку текущего публичного интерфейса Scriptura AI:

title — короткий сильный заголовок;
anchor — конкретная цитата/опора из стиха;
teaser — основная мысль карточки;
why_it_matters — коротко, что меняется в чтении или восприятии.

Карточка должна быть цельной, но не превращай teaser в длинную статью. Расширенная статья генерируется отдельным механизмом.`;

function buildUserPrompt(ctx: PearlV3VerseContext, angle: PearlV3Angle): string {
  return `ВХОДНЫЕ ДАННЫЕ

Стих: ${ctx.centralRef}
«${ctx.centralText}»

Угол наблюдения:
Якорь: ${angle.anchor}
Наблюдение: ${angle.observation}
Почему интересно: ${angle.whyInteresting}

ЗАДАЧА

Преврати этот угол в сильную публичную карточку Scriptura AI.

Верни ТОЛЬКО валидный JSON-объект. Ничего до или после JSON. Не оборачивай ответ в markdown или блок кода. Не добавляй комментарии или лишние ключи.

Структура строго такая:

{
  "title": "<одна сильная фраза, передающая суть открытия. Не вопрос, не призыв. Утверждение или образ. 5-12 слов.>",
  "anchor": "<короткая цитата из стиха или конкретное место — то, на что физически опирается карточка. 1-2 строки.>",
  "teaser": "<4-7 предложений. Раскрой угол как тихое наблюдение. Не пересказывай стих. Покажи читателю то, что он мог не заметить. Образ допустим только если он рождается из текста, а не украшает его сбоку.>",
  "why_it_matters": "<1-3 предложения о том, что меняется в чтении, восприятии или практике веры после этого сдвига. Не мораль и не вывод 'отсюда следует'.>"
}

НЕ ДЕЛАЙ

- Не пересказывай стих своими словами вместо раскрытия угла.
- Не используй слова «удивительно», «прекрасно», «потрясающе» — пусть удивление возникает у читателя, не у автора.
- Не начинай с «Этот стих учит нас...» или «Здесь мы видим...».
- Не вводи богословские термины, которых нет в самом стихе или проверенной опоре.
- Не цитируй стих целиком, если можно дать короткую опору.
- Не исправляй угол на другой: работай именно с данным наблюдением.`;
}

export async function runPearlV3Writer(
  ctx: PearlV3VerseContext,
  angle: PearlV3Angle,
): Promise<{ rawOutput: string; card: PearlV3CardDraft | null }> {
  const rawOutput = await callPearlClaude({
    system: SYSTEM,
    user: buildUserPrompt(ctx, angle),
    maxTokens: 2200,
  });

  return {
    rawOutput,
    card: parseCard(rawOutput),
  };
}

function parseCard(raw: string): PearlV3CardDraft | null {
  const cleaned = raw
    .trim()
    .replace(/^```(?:json)?\s*/i, "")
    .replace(/\s*```$/i, "")
    .trim();

  try {
    const parsed = JSON.parse(cleaned) as Partial<
      Record<keyof PearlV3CardDraft, unknown>
    >;

    const title = toNonEmptyString(parsed.title);
    const anchor = toNonEmptyString(parsed.anchor);
    const teaser = toNonEmptyString(parsed.teaser);
    const why = toNonEmptyString(parsed.why_it_matters);

    if (!title || !anchor || !teaser || !why) return null;

    return {
      title,
      anchor,
      teaser,
      why_it_matters: why,
    };
  } catch {
    return null;
  }
}

function toNonEmptyString(value: unknown): string | null {
  if (typeof value !== "string") return null;
  const trimmed = value.trim();
  return trimmed ? trimmed : null;
}
